// Percursos de demonstração (brief, secção 10). Uso: node tests/percurso.spec.cjs [url]
// Requer Playwright e o servidor local (npm start), que reproduz a regra SPA da Netlify.
const { chromium, devices } = require('playwright');
const assert = require('node:assert/strict');

const BASE = (process.argv[2] || 'http://localhost:8080/').replace(/\/$/, '');
const OUT = process.env.SHOTS || null;
let n = 0;
const ok = (m) => { n += 1; console.log('  ✓ ' + m); };
const euros = (t) => t.replace(/\s/g, ' ').trim();
const IPAD_H = { viewport: { width: 1180, height: 820 }, hasTouch: true, userAgent: devices['iPad Pro 11'].userAgent };

(async () => {
  const browser = await chromium.launch();
  const erros = [];
  const nova = async (opts = {}) => {
    const ctx = await browser.newContext({ viewport: { width: 1180, height: 820 }, ...opts });
    const p = await ctx.newPage();
    p.on('pageerror', (e) => erros.push(e.message));
    p.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) erros.push(m.text()); });
    return p;
  };
  const contador = (p) => p.textContent('[data-num-cesto]');
  const subtotal = async (p) => euros(await p.textContent('[data-subtotal]'));

  console.log('A. iPad horizontal: Mercado → Padaria → broa → voltar à posição');
  let p = await nova(IPAD_H);
  await p.goto(BASE + '/', { waitUntil: 'networkidle' });
  const topoCartao = await p.$eval('.grelha--hoje .cartao__nome', (e) => e.getBoundingClientRect().top);
  assert.ok(topoCartao < 820, 'há produtos compráveis no primeiro ecrã: ' + topoCartao);
  ok(`primeiro ecrã mostra o nome do primeiro produto (a ${Math.round(topoCartao)} px)`);
  await p.tap('[data-sub="mega-mercado"]');
  assert.equal(await p.getAttribute('[data-sub="mega-mercado"]', 'aria-expanded'), 'true');
  assert.ok(await p.isVisible('#mega-mercado'));
  if (OUT) await p.screenshot({ path: `${OUT}/a-megamenu-ipad.png` });
  await p.tap('#mega-mercado >> text=Padaria');
  await p.waitForURL('**/mercado/padaria');
  assert.equal(await p.textContent('h1'), 'Padaria');
  assert.equal(await p.isVisible('#mega-mercado'), false);
  const broa = p.locator('.cartao__nome a', { hasText: 'Broa de milho' });
  await broa.scrollIntoViewIfNeeded();
  await p.evaluate(() => window.scrollBy(0, 120));
  const y = await p.evaluate(() => window.scrollY);
  await broa.tap();
  await p.waitForURL('**/produto/broa-de-milho');
  assert.equal(await p.textContent('h1'), 'Broa de milho');
  await p.goBack();
  await p.waitForURL('**/mercado/padaria');
  await p.waitForTimeout(300);
  const y2 = await p.evaluate(() => window.scrollY);
  assert.ok(Math.abs(y2 - y) < 30, `posição recuperada (${y} → ${y2})`);
  ok('megamenu por toque, Padaria, broa e regresso à mesma posição');

  console.log('B. Pesquisa “pao” e “grao”, resultado, filtros no URL');
  await p.goto(BASE + '/', { waitUntil: 'networkidle' });
  await p.fill('#pesquisa-topo', 'pao');
  await p.waitForSelector('#pesquisa-topo-lista [role="option"]');
  assert.ok((await p.textContent('#pesquisa-topo-lista')).includes('Pão de fermentação lenta'));
  await p.press('#pesquisa-topo', 'Enter');
  await p.waitForURL('**/pesquisa?q=pao');
  const nomesPao = await p.$$eval('[data-grelha] .cartao__nome', (a) => a.map((x) => x.textContent));
  assert.ok(nomesPao.includes('Pão de fermentação lenta') && nomesPao.includes('Broa de milho'), 'pao encontra pão e a banca da padaria');
  await p.fill('#pesquisa-topo', 'grao');
  await p.press('#pesquisa-topo', 'Enter');
  await p.waitForURL('**/pesquisa?q=grao');
  assert.ok((await p.$$eval('[data-grelha] .cartao__nome', (a) => a.map((x) => x.textContent))).includes('Grão-de-bico seco'));
  await p.click('.cartao__nome a:has-text("Grão-de-bico seco")');
  await p.waitForURL('**/produto/grao-de-bico-seco');
  await p.goBack();
  await p.goto(BASE + '/pesquisa?q=pao', { waitUntil: 'networkidle' });
  await p.click('.filtros-lateral label:has-text("Padaria do Largo")');
  await p.click('.filtros-lateral label:has-text("2 € a 5 €")');
  await p.selectOption('[data-ordem]', 'preco-asc');
  const url = p.url();
  assert.match(url, /q=pao/); assert.match(url, /produtor=padaria-do-largo/); assert.match(url, /preco=2-5/); assert.match(url, /ordem=preco-asc/);
  const lista1 = await p.$$eval('[data-grelha] .cartao__nome', (a) => a.map((x) => x.textContent));
  const p2 = await nova();
  await p2.goto(url, { waitUntil: 'networkidle' });
  const lista2 = await p2.$$eval('[data-grelha] .cartao__nome', (a) => a.map((x) => x.textContent));
  assert.deepEqual(lista2, lista1);
  assert.ok(await p2.isChecked('.filtros-lateral input[value="padaria-do-largo"]'));
  ok(`“pao” e “grao” encontram pão e grão; o URL reproduz a seleção (${lista1.length} resultados)`);
  await p2.context().close();

  console.log('C. Cesto: 2 pães + 1 cabaz de pão e horta = 30,60 €; 1 pão = 25,80 €');
  await p.evaluate(() => localStorage.clear());
  await p.goto(BASE + '/produto/pao-fermentacao-lenta', { waitUntil: 'networkidle' });
  await p.click('[data-q="1"]');
  assert.match(await p.textContent('[data-resumo]'), /2 pães de 750 g/);
  await p.click('[data-add-ficha]');
  await p.goto(BASE + '/produto/cabaz-pao-e-horta', { waitUntil: 'networkidle' });
  assert.ok(await p.isVisible('#dentro-titulo'));
  await p.click('[data-add-ficha]');
  assert.equal(await contador(p), '3');
  await p.click('.cab__cesto');
  assert.equal(await subtotal(p), '30,60 €');
  await p.click('[aria-label="Menos uma unidade de Pão de fermentação lenta"]');
  assert.equal(await subtotal(p), '25,80 €');
  assert.equal(await contador(p), '2');
  ok('3 unidades e 30,60 €; depois 25,80 €');
  await p.keyboard.press('Escape');

  console.log('D. Configurador: pão + broa + cenouras = 10,60 €, guardar, cesto, editar → 7,00 €');
  await p.evaluate(() => localStorage.clear());
  await p.goto(BASE + '/cabazes/compor?partida=vazio', { waitUntil: 'networkidle' });
  await p.click('[data-banca="padaria"]');
  await p.click('.linha-p:has-text("Pão de fermentação lenta") .btn-juntar');
  await p.click('.linha-p:has-text("Broa de milho") .btn-juntar');
  await p.click('[data-banca="horticolas"]');
  await p.click('.linha-p:has-text("Cenouras com rama") .btn-juntar');
  assert.equal(euros(await p.textContent('.compor__resumo [data-total]')), '10,60 €');
  await p.click('.compor__resumo [data-guardar]');
  await p.fill('[data-confirmar] input[name="nome"]', 'O meu cabaz de sábado');
  await p.click('[data-confirmar] button[type="submit"]');
  assert.match(await p.textContent('.compor__resumo [data-estado]'), /Guardada/);
  await p.click('.compor__resumo [data-adicionar]');
  assert.equal(await contador(p), '1');
  await p.click('.cab__cesto');
  assert.equal(await subtotal(p), '10,60 €');
  if (OUT) await p.screenshot({ path: `${OUT}/d-cesto-grupo.png` });
  await p.click('.linha__editar');
  await p.waitForURL(/\/cabazes\/compor/);
  await p.click('.compor__resumo [aria-label="Tirar da caixa: Broa de milho"]');
  assert.equal(euros(await p.textContent('.compor__resumo [data-total]')), '7,00 €');
  const itensAntes = await p.evaluate(() => JSON.parse(localStorage.getItem('dhf-cesto-v2')).linhas[0].itens.length);
  assert.equal(itensAntes, 3, 'o cesto só muda depois de confirmar');
  await p.click('.compor__resumo [data-atualizar]');
  await p.click('[data-confirmar] [data-res="sim"]');
  await p.click('.cab__cesto');
  assert.equal(await subtotal(p), '7,00 €');
  assert.equal(await p.$$eval('.linha--grupo', (l) => l.length), 1, 'sem duplicar o grupo');
  assert.equal(await contador(p), '1');
  ok('10,60 € guardado e no cesto; editado para 7,00 € no mesmo grupo');
  await p.keyboard.press('Escape');

  console.log('E. Favorito e composição sobrevivem; concluir limpa só o cesto');
  await p.goto(BASE + '/mercado/fruta', { waitUntil: 'networkidle' });
  await p.click('[data-produto="pera-rocha"] [data-acao="fav"]');
  assert.equal(await p.textContent('[data-num-fav]'), '1');
  await p.reload({ waitUntil: 'networkidle' });
  assert.equal(await p.textContent('[data-num-fav]'), '1');
  await p.goto(BASE + '/cabazes/guardados', { waitUntil: 'networkidle' });
  assert.equal(await p.$$eval('.guardado', (l) => l.length), 1);
  await p.click('.cab__cesto');
  await p.click('[data-rever]');
  assert.match(await p.textContent('[data-gaveta-cesto]'), /Recolha \(simulada\)/);
  assert.match(await p.textContent('[data-gaveta-cesto]'), /Demonstração de conceito/);
  await p.click('[data-concluir]');
  assert.equal(await p.textContent('[data-msg-final]'), 'Demonstração concluída. Não foi efetuada qualquer cobrança ou encomenda.');
  assert.equal(await contador(p), '0');
  await p.keyboard.press('Escape');
  await p.reload({ waitUntil: 'networkidle' });
  assert.equal(await p.textContent('[data-num-fav]'), '1');
  assert.equal(await p.$$eval('.guardado', (l) => l.length), 1);
  assert.equal(await contador(p), '0');
  ok('favorito e composição preservados; cesto limpo após concluir');

  console.log('F. Receita: dois ingredientes → embalagens e total certos');
  await p.goto(BASE + '/receitas/torrada-de-queijo-de-cabra-e-compota-de-figo', { waitUntil: 'networkidle' });
  await p.click('.ingr:has-text("pão de centeio") .ingr__rotulo');
  await p.click('.ingr:has-text("compota de figo") .ingr__rotulo');
  assert.match(await p.textContent('[data-add-receita]'), /2 artigos ao cesto · 8,10/);
  await p.click('[data-add-receita]');
  await p.click('.cab__cesto');
  assert.equal(await subtotal(p), '8,10 €');
  const nomes = await p.$$eval('.linha .linha__nome', (l) => l.map((x) => x.textContent));
  assert.deepEqual(nomes.sort(), ['Compota de figo', 'Pão de centeio']);
  ok('Pão de centeio (3,90 €) + Compota de figo (4,20 €) = 8,10 €');
  await p.keyboard.press('Escape');

  console.log('Links diretos e atualização de páginas internas (regra SPA)');
  for (const r of ['/mercado/padaria?preco=2-5', '/produto/broa-de-milho', '/produtores/queijaria-da-serra', '/receitas/tiborna-de-azeite-e-alecrim', '/cabazes/guardados']) {
    await p.goto(BASE + r, { waitUntil: 'networkidle' });
    await p.reload({ waitUntil: 'networkidle' });
    assert.notEqual(await p.textContent('h1'), 'Esta banca não existe', r);
  }
  ok('cinco destinos internos abrem diretamente e após atualizar');

  console.log('Teclado e telemóvel: menu em painel com níveis, Escape e foco');
  const m = await nova({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  await m.goto(BASE + '/', { waitUntil: 'networkidle' });
  await m.click('[data-abrir-menu]');
  await m.click('[data-nivel="mercado"]');
  assert.equal(await m.textContent('#painel-menu-titulo'), 'Mercado');
  assert.match(await m.textContent('.painel__trilho'), /Menu › Mercado/);
  await m.keyboard.press('Escape');
  assert.equal(await m.textContent('#painel-menu-titulo'), 'Menu');
  await m.click('[data-nivel="mercado"]');
  await m.click('.painel__link:has-text("Fruta")');
  await m.waitForURL('**/mercado/fruta');
  assert.equal(await m.isVisible('[data-painel-menu]'), false);
  await m.goBack();
  await m.waitForURL(BASE + '/');
  if (OUT) await m.screenshot({ path: `${OUT}/telemovel-inicio.png` });
  await m.goto(BASE + '/', { waitUntil: 'networkidle' });
  const desk = await nova({ viewport: { width: 1440, height: 900 } });
  await desk.goto(BASE + '/', { waitUntil: 'networkidle' });
  await desk.focus('[data-sub="mega-mercado"]');
  await desk.keyboard.press('Enter');
  assert.ok(await desk.isVisible('#mega-mercado'));
  await desk.keyboard.press('Escape');
  assert.equal(await desk.isVisible('#mega-mercado'), false);
  assert.equal(await desk.evaluate(() => document.activeElement.dataset.sub), 'mega-mercado');
  ok('painel móvel com níveis e voltar; megamenu por teclado com Escape e foco devolvido');

  assert.deepEqual([...new Set(erros)], [], 'sem erros de JavaScript');
  ok('sem erros de JavaScript');
  await browser.close();
  console.log(`\n${n} verificações passaram.`);
})().catch(async (e) => { console.error('\n✗ FALHOU:', e.message); process.exit(1); });
